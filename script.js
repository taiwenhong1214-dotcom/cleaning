  async function sendMessage() {
      const inputField = document.getElementById('user-input');
      const messageText = inputField.value.trim();
      if (!messageText) return;

      addMessageToChat(messageText, 'user-message');
      inputField.value = '';
      conversationHistory.push({ "role": "user", "content": messageText });

      const currentLang = localStorage.getItem('hc_lang') || 'en';
      const typingId = addMessageToChat(translations[currentLang].chat_typing, 'bot-message');

      try {
          const response = await fetch('/api/chat', {
              method: 'POST',
              headers: { 'Content-Type': 'application/json' },
              body: JSON.stringify({ messages: conversationHistory })
          });

          const data = await response.json();
          document.getElementById(typingId).remove();

          if (data.choices && data.choices.length > 0) {
              const botReply = data.choices[0].message.content;
              conversationHistory.push({ "role": "assistant", "content": botReply });
              addMessageToChat(botReply, 'bot-message');
          } else {
              addMessageToChat(translations[currentLang].chat_err_sys, 'bot-message');
          }
      } catch (error) {
          console.error("API Error:", error);
          document.getElementById(typingId).remove();
          addMessageToChat(translations[currentLang].chat_err_net, 'bot-message');
      }
  }

  function addMessageToChat(text, className) {
      const chatContent = document.getElementById('chat-content');
      const messageDiv = document.createElement('div');
      const msgId = 'msg-' + Date.now();
      messageDiv.id = msgId;
      messageDiv.className = 'message ' + className;
      messageDiv.innerHTML = text; // 改为 innerHTML 适配可能存在的标签
      chatContent.appendChild(messageDiv);
      chatContent.scrollTop = chatContent.scrollHeight;
      return msgId;
  }

