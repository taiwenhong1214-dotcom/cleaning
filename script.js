  function changeLang(lang) {
    const t = translations[lang];
    if (!t) return;

    localStorage.setItem('hc_lang', lang);
    document.documentElement.lang = lang;
    
    // 更新选择器
    const langSelect = document.getElementById('langSelect');
    if (langSelect) langSelect.value = lang;

    // 更新内部文字 (innerHTML)
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (t[key]) el.innerHTML = t[key];
    });

    // 更新占位符 (Placeholders)
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (t[key]) el.placeholder = t[key];
    });

    // 动态更新 WhatsApp 悬浮按钮链接
    const floatWa = document.getElementById('floatWaLink');
    if (floatWa && t.wa_float_msg) {
      floatWa.href = `https://api.whatsapp.com/send?phone=60122911406&text=${encodeURIComponent(t.wa_float_msg)}`;
    }
    
    const navMenu = document.getElementById('navLinks');
    const hamburgerBtn = document.getElementById('hamburger');
    if (navMenu && navMenu.classList.contains('show-mobile')) {
      navMenu.classList.remove('show-mobile');
      if (hamburgerBtn) hamburgerBtn.style.transform = 'rotate(0deg)';
    }
  }

